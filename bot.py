bot = Bot(token=TOKEN)
dp = Dispatcher()

@dp.message(F.text)
async def handle_secret(message: Message):
    # Проверяем слово без учёта регистра и пробелов
    if message.text.strip().lower() == SECRET_WORD:
        text = random.choice(TEXTS)
        await message.reply(text)  # ответ на сообщение пользователя
    else:
        await message.answer("Неверное кодовое слово 🤫")

async def handle(request):
    return web.Response(text="Bot is running!")

async def main():
    # Запускаем бота в фоне
    asyncio.create_task(dp.start_polling(bot))
    
    # Запускаем веб-сервер
    app = web.Application()
    app.router.add_get('/', handle)
    runner = web.AppRunner(app)
    await runner.setup()
    port = int(os.getenv("PORT", 8080))
    site = web.TCPSite(runner, '0.0.0.0', port)
    await site.start()
    
    # Бесконечное ожидание
    await asyncio.Event().wait()

